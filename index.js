const express = require('express');
const cors = require('cors');
const app = express();
app.use(cors());
app.use(express.json({ limit: '10mb' }));

// ✅ API Key Environment Variable থেকে আসবে (Render Dashboard-এ সেট করা আছে)
const BREVO_API_KEY = process.env.BREVO_KEY;
const SENDER_EMAIL = "safeguard.alert.bd@gmail.com";

app.post('/send-alert', async (req, res) => {
    const { userEmail, deviceInfo } = req.body;
    if (!userEmail) return res.status(400).send('No email');

    let infoHtml = '';
    for (const [key, value] of Object.entries(deviceInfo)) {
        if (value && value.includes("https://maps.google.com")) {
            infoHtml += `<tr><td style="padding: 8px; font-weight: bold; border-bottom: 1px solid #eee;">${key}</td><td style="padding: 8px; border-bottom: 1px solid #eee;"><a href="${value}" style="color: #1a73e8;">📍 View on Google Maps</a></td></tr>`;
        } else {
            infoHtml += `<tr><td style="padding: 8px; font-weight: bold; border-bottom: 1px solid #eee;">${key}</td><td style="padding: 8px; border-bottom: 1px solid #eee;">${value}</td></tr>`;
        }
    }

    const htmlBody = `
        <div style="font-family: Arial, sans-serif; max-width: 600px; margin: auto; border: 1px solid #ddd; padding: 20px; border-radius: 10px;">
            <h2 style="color: #d32f2f; text-align: center;">⚠️ SafeGuard Intruder Alert</h2>
            <p style="text-align: center; font-size: 16px;">Someone tried to unlock your device. Here are the details:</p>
            <table style="width: 100%; border-collapse: collapse; margin-top: 20px; background-color: #f9f9f9;">
                ${infoHtml}
            </table>
            <br/>
            <p style="font-size: 12px; color: #888; text-align: center;">Generated by SafeGuard Security App</p>
        </div>
    `;

    const data = {
        sender: { name: 'SafeGuard', email: SENDER_EMAIL },
        to: [{ email: userEmail }],
        subject: '⚠️ SafeGuard Intruder Alert - Device Info',
        htmlContent: htmlBody
    };

    try {
        const r = await fetch('https://api.brevo.com/v3/smtp/email', {
            method: 'POST',
            headers: { 
                'api-key': BREVO_API_KEY, 
                'content-type': 'application/json' 
            },
            body: JSON.stringify(data)
        });
        
        if (!r.ok) {
            const errorText = await r.text();
            return res.status(500).json({ ok: false, error: errorText });
        }
        res.status(200).json({ ok: true });
    } catch (error) {
        res.status(500).json({ ok: false, error: error.message });
    }
});

app.listen(process.env.PORT || 3000, () => {
    console.log("SafeGuard Server running");
});
